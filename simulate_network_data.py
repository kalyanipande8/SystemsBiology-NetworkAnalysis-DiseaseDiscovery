"""
Simulate a synthetic protein-protein-interaction (PPI)-like network with
realistic scale-free topology, embed disease-associated modules tied to
distinct rare-disease phenotypes, and generate a patient cohort with
per-patient omics perturbation profiles.

DISCLAIMER: This is a portfolio/demo project. The network, gene names,
disease modules, phenotypes, and patient omics profiles below are entirely
SYNTHETIC, generated by this script with a fixed random seed. No real gene
interaction data, patient data, or proprietary/employer data is used. The
general approach (scale-free PPI backbone, seeded disease modules, network
diffusion for module/patient analysis) reflects published network-medicine
concepts (e.g. Barabasi & Oltvai 2004; Menche et al. 2015 "Uncovering
disease-disease relationships"), not any specific real dataset.

Run directly to regenerate data/network.gpickle-equivalent (edge list),
data/patients.csv, and data/ground_truth_modules.csv.
"""

import json
import random
from pathlib import Path

import networkx as nx
import numpy as np

SEED = 42
N_NODES = 600
BA_M = 2                    # Barabasi-Albert attachment parameter -> scale-free degree dist
N_PHENOTYPES = 12
MODULE_SIZE_RANGE = (14, 26)
N_PATIENTS = 156             # 13 patients per phenotype
BACKGROUND_NOISE_GENES = (2, 5)   # random off-module perturbations per patient
MODULE_DROPOUT_PROB = 0.30  # patient does not express every module gene (incomplete penetrance)
CROSS_MODULE_LEAK_PROB = 0.08  # small chance a neighboring-module gene also perturbed (comorbidity/pleiotropy)

DATA_DIR = Path(__file__).parent / "data"

PHENOTYPE_NAMES = [
    "Mitochondrial myopathy",
    "Lysosomal storage disorder",
    "Ciliopathy",
    "Skeletal dysplasia",
    "Congenital neuromuscular syndrome",
    "Metabolic acidemia",
    "Peroxisomal disorder",
    "Connective tissue disorder",
    "Immune dysregulation syndrome",
    "Cardiomyopathy (inherited)",
    "Neurodevelopmental disorder",
    "Retinal dystrophy",
]

assert len(PHENOTYPE_NAMES) == N_PHENOTYPES


def build_ppi_network(seed=SEED):
    """Barabasi-Albert graph: genuine preferential-attachment growth model,
    giving a heavy-tailed (scale-free-ish) degree distribution characteristic
    of real PPI networks (few hub proteins, many low-degree proteins)."""
    G = nx.barabasi_albert_graph(N_NODES, BA_M, seed=seed)
    mapping = {i: f"GENE{i:04d}" for i in G.nodes()}
    G = nx.relabel_nodes(G, mapping)
    return G


def seed_disease_modules(G, rng):
    """Pick N_PHENOTYPES disjoint seed communities and densify them with extra
    intra-module edges so they behave like genuine topological disease
    modules (denser-than-random subgraphs), per the network-medicine
    "disease module" hypothesis (Menche et al. 2015)."""
    nodes = list(G.nodes())
    rng.shuffle(nodes)
    modules = {}
    used = set()
    idx = 0
    for phenotype in PHENOTYPE_NAMES:
        size = rng.randint(*MODULE_SIZE_RANGE)
        picked = []
        while len(picked) < size and idx < len(nodes):
            n = nodes[idx]
            idx += 1
            if n not in used:
                picked.append(n)
                used.add(n)
        modules[phenotype] = picked

    # Densify: add extra edges within each module to create real topological
    # cohesion (so community detection / diffusion has genuine signal to find).
    for phenotype, genes in modules.items():
        extra_target = int(len(genes) * 1.8)
        added = 0
        attempts = 0
        while added < extra_target and attempts < extra_target * 20:
            a, b = rng.sample(genes, 2)
            attempts += 1
            if not G.has_edge(a, b):
                G.add_edge(a, b)
                added += 1
    return modules


def simulate_patients(G, modules, rng, np_rng):
    """Each patient is assigned one 'ground truth' phenotype/module. Their
    perturbed-gene set = a stochastic (incomplete-penetrance) subset of that
    module's genes, plus a small amount of cross-module leakage (comorbidity/
    pleiotropy) and independent background noise, mimicking real omics
    perturbation calls (e.g. rare damaging variants / outlier expression)."""
    all_module_genes = {p: set(g) for p, g in modules.items()}
    phenotypes = list(modules.keys())
    all_genes = list(G.nodes())

    patients = []
    per_phenotype = N_PATIENTS // N_PHENOTYPES
    pid = 0
    for phenotype in phenotypes:
        for _ in range(per_phenotype):
            pid += 1
            core = [g for g in all_module_genes[phenotype] if np_rng.random() > MODULE_DROPOUT_PROB]
            if not core:  # guarantee at least 2 genes hit
                core = list(rng.sample(list(all_module_genes[phenotype]), 2))

            leak = []
            other_phenotypes = [p for p in phenotypes if p != phenotype]
            for other in other_phenotypes:
                for g in all_module_genes[other]:
                    if np_rng.random() < CROSS_MODULE_LEAK_PROB / len(other_phenotypes):
                        leak.append(g)

            n_noise = rng.randint(*BACKGROUND_NOISE_GENES)
            noise = rng.sample(all_genes, n_noise)

            perturbed = sorted(set(core) | set(leak) | set(noise))
            patients.append({
                "patient_id": f"P{pid:04d}",
                "true_phenotype": phenotype,
                "perturbed_genes": perturbed,
            })
    return patients


def main():
    DATA_DIR.mkdir(exist_ok=True)
    random.seed(SEED)
    np.random.seed(SEED)
    rng = random.Random(SEED)
    np_rng = np.random.default_rng(SEED)

    G = build_ppi_network()
    modules = seed_disease_modules(G, rng)
    patients = simulate_patients(G, modules, rng, np_rng)

    nx.write_edgelist(G, DATA_DIR / "ppi_network.edgelist", data=False)

    with open(DATA_DIR / "ground_truth_modules.json", "w") as f:
        json.dump(modules, f, indent=2)

    with open(DATA_DIR / "patients.json", "w") as f:
        json.dump(patients, f, indent=2)

    print(f"Network: {G.number_of_nodes()} nodes, {G.number_of_edges()} edges")
    degs = [d for _, d in G.degree()]
    print(f"Degree range: min={min(degs)}, max={max(degs)}, mean={np.mean(degs):.2f}")
    print(f"Seeded {len(modules)} ground-truth disease modules "
          f"(sizes: {[len(v) for v in modules.values()]})")
    print(f"Simulated {len(patients)} patients across {N_PHENOTYPES} phenotypes")
    return G, modules, patients


if __name__ == "__main__":
    main()
